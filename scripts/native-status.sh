#!/usr/bin/env bash
# kube-effect — state of the optional Kube Effect Plus KCM (ADR-012/ADR-018).
#
#   make native-status
#
# Prints the stamp written by native/build.sh and compares it with the Plasma
# and Qt versions installed right now. Plasma has no stable ABI across releases,
# so a mismatch means rebuild: exit 1. A missing stamp or a missing .so also
# exits 1; only a matching, installed build is OK.
set -u

DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/kube-effect"
STAMP="$DATA_DIR/native-stamp.json"

current_plasma() {
    local output
    output=$(kwin_wayland --version 2>/dev/null) || return 1
    printf '%s\n' "$output" | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1
}

current_qt() {
    if command -v qmake6 >/dev/null 2>&1; then
        qmake6 -query QT_VERSION 2>/dev/null && return 0
    fi
    pkg-config --modversion Qt6Core 2>/dev/null
}

plasma=$(current_plasma)
qt=$(current_qt)
echo "system: Plasma/KWin ${plasma:-unknown} · Qt ${qt:-unknown}"

if [ ! -f "$STAMP" ]; then
    echo "stamp:  missing ($STAMP)"
    echo "RESULT: Kube Effect Plus not built — run: make native"
    exit 1
fi

json_field() {
    python3 -c 'import json,sys;print(json.load(open(sys.argv[1])).get(sys.argv[2],""))' "$STAMP" "$1"
}

stamp_plasma=$(json_field plasma)
stamp_qt=$(json_field qt)
stamp_prefix=$(json_field prefix)
echo "stamp:  Plasma $stamp_plasma · Qt $stamp_qt · package $(json_field pkg)"
echo "        built $(json_field built) into $stamp_prefix"

status=0
if [ "$stamp_plasma" != "$plasma" ]; then
    echo "STALE:  Plasma compiled=$stamp_plasma current=${plasma:-?} — run: make native"
    status=1
fi
if [ "$stamp_qt" != "$qt" ]; then
    echo "STALE:  Qt compiled=$stamp_qt current=${qt:-?} — run: make native"
    status=1
fi

plugin=""
prefix_sh="$DATA_DIR/prefix.sh"
if [ -f "$prefix_sh" ]; then
    # prefix.sh (generated by ECM) knows the exact Qt plugin dir of this prefix.
    plugindir=$(sed -n 's/^export QT_PLUGIN_PATH=\([^:]*\).*/\1/p' "$prefix_sh" | head -1)
    if [ -n "$plugindir" ] && [ -f "$plugindir/plasma/kcms/systemsettings/kcm_kube_effect_plus.so" ]; then
        plugin="$plugindir/plasma/kcms/systemsettings/kcm_kube_effect_plus.so"
    fi
fi
if [ -z "$plugin" ]; then
    for candidate in "$stamp_prefix/lib/plugins" "$stamp_prefix/lib/qt6/plugins" "$stamp_prefix/lib64/plugins" "$stamp_prefix/lib64/qt6/plugins"; do
        if [ -f "$candidate/plasma/kcms/systemsettings/kcm_kube_effect_plus.so" ]; then
            plugin="$candidate/plasma/kcms/systemsettings/kcm_kube_effect_plus.so"
            break
        fi
    done
fi
if [ -n "$plugin" ]; then
    echo "plugin: $plugin"
else
    echo "plugin: Kube Effect Plus not found under $stamp_prefix (reinstall: make native)"
    status=1
fi

if [ "$status" -eq 0 ]; then
    echo "RESULT: Kube Effect Plus up to date."
else
    echo "RESULT: Kube Effect Plus rebuild needed — make native"
fi
exit "$status"
